#!/usr/bin/env python3
"""Generate the standard test patterns deterministically (stdlib only).

Writes fixtures/patterns/<name>.pat (the engine's pattern text, read by the
renderer, the tests and the workshop) and fixtures/midi/<name>.mid (the same
notes as a Standard MIDI File, for Logic). Re-running reproduces them byte for
byte; edit the musical content here, never the generated files.
"""
from __future__ import annotations

import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTE = {n: i for i, n in enumerate("C C# D D# E F F# G G# A A# B".split())}


def m(name: str) -> int:
    """'C4' -> 60, 'F#2' -> 42."""
    pitch, octave = name[:-1], int(name[-1])
    return 12 * (octave + 1) + NOTE[pitch]


class Pattern:
    def __init__(self, name: str, title: str, purpose: str, bpm: float, length: float):
        self.name, self.title, self.purpose = name, title, purpose
        self.bpm, self.length = bpm, length
        self.notes: list[tuple[float, float, int, int]] = []

    def add(self, start: float, dur: float, notes, vel: int = 90):
        for n in [notes] if isinstance(notes, (int, str)) else notes:
            self.notes.append((start, dur, m(n) if isinstance(n, str) else n, vel))
        return self

    def pat_text(self) -> str:
        lines = [
            "# generated by tools/gen_patterns.py — edit the generator, not this file",
            f"# purpose: {self.purpose}",
            f"name   {self.title}",
            f"bpm    {self.bpm:g}",
            f"length {self.length:g}",
        ]
        for s, d, n, v in sorted(self.notes):
            lines.append(f"note {s:g} {d:g} {n} {v}")
        return "\n".join(lines) + "\n"

    def midi_bytes(self, ppq: int = 480) -> bytes:
        events = []
        for s, d, n, v in self.notes:
            events.append((round(s * ppq), 1, n, v))
            events.append((round(min(s + d, self.length) * ppq), 0, n, 0))
        events.sort(key=lambda e: (e[0], e[1]))  # offs first at equal ticks
        track = bytearray()
        tempo = round(60_000_000 / self.bpm)
        track += b"\x00\xff\x51\x03" + tempo.to_bytes(3, "big")
        name = self.title.encode()
        track += b"\x00\xff\x03" + vlq(len(name)) + name
        last = 0
        for tick, on, n, v in events:
            track += vlq(tick - last) + bytes([0x90 if on else 0x80, n, v if on else 64])
            last = tick
        end = round(self.length * ppq)
        track += vlq(max(0, end - last)) + b"\xff\x2f\x00"
        return (b"MThd" + struct.pack(">IHHH", 6, 0, 1, ppq)
                + b"MTrk" + struct.pack(">I", len(track)) + bytes(track))


def vlq(value: int) -> bytes:
    out = [value & 0x7F]
    value >>= 7
    while value:
        out.append((value & 0x7F) | 0x80)
        value >>= 7
    return bytes(reversed(out))


def patterns() -> list[Pattern]:
    out = []

    # Soft sustained chords: Cmaj7 - Am9 - Fmaj7 - G6, voiced close, legato.
    p = Pattern("pad_chords", "Soft sustained chords",
                "pads, slow attack/release, harmonic smoothness", 72, 16)
    for i, chord in enumerate([["C3", "G3", "B3", "E4"], ["A2", "E3", "B3", "C4"],
                               ["F2", "C3", "E3", "A3"], ["G2", "D3", "E3", "B3"]]):
        p.add(4 * i, 3.9, chord, 70)
    out.append(p)

    # Tight repeated chords: off-beat stabs, Am - F - C - G.
    p = Pattern("tight_chords", "Tight repeated chords",
                "supersaw-style stabs, note transitions, polyphony", 122, 16)
    prog = [["A3", "C4", "E4"], ["F3", "A3", "C4"], ["C4", "E4", "G4"], ["G3", "B3", "D4"]]
    for bar, chord in enumerate(prog):
        for k in range(8):
            if k in (0, 3, 6, 7) or (k == 4 and bar % 2):
                p.add(4 * bar + 0.5 * k, 0.38, chord + [chord[0][:-1] + "2"], 100 if k == 0 else 82)
    out.append(p)

    # Lead melody in A minor, mixed lengths, a leap and a held note.
    p = Pattern("lead_melody", "Lead melody",
                "pitch tracking, articulation, legato vs detached", 96, 16)
    tune = [("E4", 1), ("A4", 0.5), ("B4", 0.5), ("C5", 1.5), ("B4", 0.5), ("A4", 1), ("G4", 1),
            ("E4", 2), ("D4", 0.5), ("E4", 0.5), ("G4", 1), ("A4", 1.5), ("C5", 0.5), ("E5", 2),
            ("D5", 1), ("C5", 1)]
    t = 0.0
    for note, dur in tune:
        p.add(t, dur * 0.92, note, 96)
        t += dur
    p.length = t
    out.append(p)

    # Short staccato notes: 16th plucks on a pentatonic figure.
    p = Pattern("staccato", "Short staccato notes",
                "attack behaviour, fast release, percussive patches", 110, 8)
    figure = ["A3", "C4", "D4", "E4", "G4", "E4", "D4", "C4"]
    for k in range(32):
        p.add(0.25 * k, 0.11, figure[k % 8], 70 + (k % 4 == 0) * 40)
    out.append(p)

    # Fast repeated notes: the same pitch re-struck (envelope retrigger).
    p = Pattern("fast_repeats", "Fast repeated notes",
                "voice handling and envelope retriggering", 140, 8)
    for k in range(32):
        p.add(0.25 * k, 0.2, "E3" if k % 8 < 6 else "E4", 110 if k % 4 == 0 else 75)
    out.append(p)

    # Wide-register arpeggio: C major over five octaves, up and down.
    p = Pattern("wide_arpeggio", "Wide-register arpeggio",
                "aliasing, frequency response, pitch consistency", 100, 16)
    up = [o * 12 + i for o in range(3, 8) for i in (0, 4, 7)]  # C2..G6 as midi
    up = [n + 0 for n in up] + [m("C7")]
    seq = up + up[-2:0:-1]
    for k, n in enumerate(seq[:64]):
        p.add(0.25 * k, 0.24, n, 88)
    out.append(p)

    # Dense overlapping notes: clusters well past eight voices.
    p = Pattern("dense_overlap", "Dense overlapping notes",
                "polyphony limits, voice stealing, output safety", 88, 16)
    clusters = [["C2", "C3", "G3", "C4", "D4", "E4", "G4", "B4", "D5", "E5"],
                ["F2", "F3", "A3", "C4", "E4", "G4", "A4", "C5", "E5", "G5", "A5"],
                ["D2", "A2", "D3", "F3", "A3", "C4", "E4", "F4", "A4", "D5", "F5", "A5"]]
    for i, cl in enumerate(clusters):
        for j, n in enumerate(cl):
            p.add(5 * i + 0.08 * j, 4.6, n, 100)  # rolled, overlapping the next
    p.length = 16
    out.append(p)

    # --- drum beats (General MIDI drum map: 36 kick, 38 snare, 39 clap,
    # 42 closed hat, 46 open hat, 41/45/48 toms, 37 rim) ---
    K, S, CL, HC, HO, TL, TM, TH, RIM = 36, 38, 39, 42, 46, 41, 45, 48, 37

    p = Pattern("drums_rock", "Drums: rock beat", "kick/snare backbeat, 8th hats, a fill (drum kit)", 100, 8)
    for bar in range(2):
        b0 = 4 * bar
        for k in range(8):
            p.add(b0 + 0.5 * k, 0.25, HC, 100 if k % 2 == 0 else 72)
        for t in (0, 1.5, 2.5) if bar == 0 else (0, 2.5):
            p.add(b0 + t, 0.25, K, 118)
        for t in (1, 3):
            p.add(b0 + t, 0.25, S, 112)
    for i, (t, n) in enumerate([(7.0, TH), (7.25, TH), (7.5, TM), (7.75, TL)]):
        p.add(t, 0.25, n, 96 + 6 * i)
    out.append(p)

    p = Pattern("drums_house", "Drums: four on the floor", "kick every beat, offbeat open hats, clap (drum kit)", 124, 8)
    for b in range(8):
        p.add(b, 0.25, K, 120)
        p.add(b + 0.5, 0.25, HO, 92)
        p.add(b + 0.25, 0.1, HC, 58)
        p.add(b + 0.75, 0.1, HC, 64)
        if b % 2 == 1:
            p.add(b, 0.25, CL, 108)
    out.append(p)

    p = Pattern("drums_halftime", "Drums: half-time with ghosts", "snare on 3, ghost notes, rim, tom fill (drum kit)", 84, 8)
    for bar in range(2):
        b0 = 4 * bar
        p.add(b0, 0.25, K, 124)
        p.add(b0 + 1.75, 0.25, K, 100)
        p.add(b0 + 2, 0.25, S, 120)
        for t in (0.75, 1.25, 3.25, 3.75):
            p.add(b0 + t, 0.2, S, 34)  # ghost notes
        for k in range(8):
            p.add(b0 + 0.5 * k, 0.2, HC, 86 if k % 2 == 0 else 54)
        p.add(b0 + 3.5, 0.2, RIM, 90)
    for i, (t, n) in enumerate([(7.0, TH), (7.33, TM), (7.66, TL)]):
        p.add(t, 0.3, n, 100 + 8 * i)
    out.append(p)
    return out


def main() -> None:
    pat_dir = ROOT / "fixtures" / "patterns"
    mid_dir = ROOT / "fixtures" / "midi"
    pat_dir.mkdir(parents=True, exist_ok=True)
    mid_dir.mkdir(parents=True, exist_ok=True)
    index = []
    for p in patterns():
        (pat_dir / f"{p.name}.pat").write_text(p.pat_text())
        (mid_dir / f"{p.name}.mid").write_bytes(p.midi_bytes())
        kind = "drums" if p.name.startswith("drums_") else "synth"
        index.append(f'{{"file":"{p.name}.pat","name":"{p.title}","purpose":"{p.purpose}","kind":"{kind}"}}')
    (pat_dir / "index.json").write_text("[\n  " + ",\n  ".join(index) + "\n]\n")
    print(f"wrote {len(index)} patterns to {pat_dir} and {mid_dir}")


if __name__ == "__main__":
    main()
